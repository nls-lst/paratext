"""`paratext new` — scaffold a new project package.

Generates a project directory in the current working directory:

    <name>/
        prompt.md     # the prompt (prose, for the model)
        schema.py     # the Pydantic output schema (your metadata fields)
        __init__.py   # thin wiring: schema + prompt + a source adapter -> PROJECT

The schema and prompt are the two things you actually edit; __init__.py is a
small declaration. Answers from a short questionnaire pick the source adapter.
"""

from __future__ import annotations

import re
from pathlib import Path

PROMPT_STUB = """\
You are extracting catalogue metadata from a digitised item for a library or
archive. Look at the image(s) and return a single JSON object matching the
schema. Emit JSON only — no commentary or markdown.

Describe each field and how to handle edge cases — extraction quality depends
almost entirely on this prompt:

{fields}
"""

SCHEMA_HEADER = '''\
"""Output schema for {name}.

Keep each Field(description=...) short and structural (a type/format hint or a
short example) — behaviour and edge cases belong in prompt.md, which is *also*
sent to the model, so a long description just restates the prompt in a second
voice. Keep schema, prompt, and view in step; the generated audit test guards it.
"""

from __future__ import annotations

from typing import Optional

from pydantic import BaseModel, Field


class Record(BaseModel):
    # TODO: set types + a structural description each; behaviour goes in prompt.md.
'''

# A ready-to-run guard so a field rename can't silently drift the prompt or view.
TEST_STUB = '''\
"""Guard: {ep_name}'s prompt and view stay in step with its schema.

`audit_project` checks that every field the view shows exists in the schema, and
that every model_output field is named in the prompt.
"""

from paratext.projects import audit_project

from {mod} import PROJECT


def test_project_is_consistent():
    problems = audit_project(PROJECT)
    assert not problems, "; ".join(problems)
'''

def to_module_name(name: str) -> str:
    return re.sub(r"[^0-9a-zA-Z]+", "_", name.strip().lower()).strip("_")


def _field_names(fields: list[str]) -> list[str]:
    return [to_module_name(f) for f in fields if to_module_name(f)] or ["title"]


def _render_schema(name: str, fields: list[str]) -> str:
    lines = [
        f'    {f}: Optional[str] = Field(None, description="TODO: describe {f}")'
        for f in _field_names(fields)
    ]
    return SCHEMA_HEADER.format(name=name) + "\n".join(lines) + "\n"


def _render_prompt(fields: list[str]) -> str:
    # Seed a bullet per field so the field names appear in the prompt (keeping the
    # prompt in step with the schema — and letting the generated audit test pass).
    bullets = "\n".join(
        f"- `{f}`: TODO — what to extract, and how to handle edge cases."
        for f in _field_names(fields)
    )
    return PROMPT_STUB.format(fields=bullets)


def _source_expr(kind: str, verso: bool, crop: bool) -> tuple[str, str]:
    """Return (import_name, call_expr) for the chosen source adapter."""
    if kind == "pdf":
        return "pdf_source", "pdf_source()"
    return "image_source", f"image_source(verso_filter={verso}, crop={crop})"


def render_project(
    name: str,
    *,
    kind: str = "images",
    verso: bool = False,
    crop: bool = False,
    fields: list[str] | None = None,
    pkg_dir: str = "",
    pkg_name: str = "",
):
    """Return ``{filename: content}`` for a new project. ``kind`` is
    ``"images"`` or ``"pdf"``; ``verso``/``crop`` apply to image projects;
    ``fields`` seeds the schema (defaults to a single ``title``).

    ``pkg_dir``/``pkg_name`` nest the project inside an existing package (e.g.
    ``"src/demo"``/``"demo"``), so it ships with that package and its entry
    point actually imports. Both empty = write at the root (flat layout)."""
    mod = to_module_name(name)
    ep_name = mod.replace("_", "-")
    src_import, src_call = _source_expr(kind, verso, crop)

    init_py = f'''\
"""{name} project — generated by `paratext new`. Edit schema.py and prompt.md."""

from __future__ import annotations

from paratext.projects import Project, load_prompt
from paratext.sources import {src_import}

from .schema import Record

PROJECT = Project(
    name="{ep_name}",
    schema_version="v1",
    prompt=load_prompt(__file__),
    schema=Record,
    source={src_call},
)
'''
    where = f"{pkg_dir}/{mod}" if pkg_dir else mod
    dotted = f"{pkg_name}.{mod}" if pkg_name else mod
    return {
        f"{where}/schema.py": _render_schema(name, fields or ["title"]),
        f"{where}/prompt.md": _render_prompt(fields or ["title"]),
        f"{where}/__init__.py": init_py,
        f"tests/test_{mod}_audit.py": TEST_STUB.format(ep_name=ep_name, mod=dotted),
    }


def _project_name(pyproject: Path) -> str:
    import tomllib

    try:
        return tomllib.loads(pyproject.read_text()).get("project", {}).get("name", "")
    except (OSError, tomllib.TOMLDecodeError):
        return ""


def detect_package(root: Path | None = None) -> tuple[str, str]:
    """Where a new project module should live: ``(dir prefix, import prefix)``.

    An entry point only resolves if its module is inside the *installed*
    package, so a module written beside a ``src/`` layout registers fine and
    then fails to import. Nest into the package instead. Returns ``("", "")``
    for a flat layout or no project, meaning "write at the root"."""
    root = root or Path.cwd()
    src = root / "src"
    if src.is_dir():
        pkgs = sorted(p for p in src.iterdir() if (p / "__init__.py").is_file())
        if len(pkgs) == 1:
            return f"src/{pkgs[0].name}", pkgs[0].name
        return "", ""  # ambiguous: don't guess which package owns the project
    name = _project_name(root / "pyproject.toml")
    if name:
        cand = root / to_module_name(name)
        if (cand / "__init__.py").is_file():
            return cand.name, cand.name
    return "", ""


# A minimal packaged project, so a scaffold in an empty directory is runnable
# rather than merely written. Flat layout: the project module sits at the root
# and is packaged by name, which is the layout `paratext new` writes into.
BOOTSTRAP_PYPROJECT = '''\
[project]
name = "{name}"
version = "0.1.0"
requires-python = ">=3.11"
dependencies = ["paratext"]

# paratext is resolved from git, not PyPI, where the name belongs to an
# unrelated package. Declared as a uv source rather than a direct reference in
# `dependencies` so the build backend stays happy; if you install with pip
# instead of uv, install paratext from the URL below yourself.
[tool.uv.sources]
paratext = {{ git = "https://github.com/nls-lst/paratext" }}

[build-system]
requires = ["hatchling"]
build-backend = "hatchling.build"

[tool.hatch.build.targets.wheel]
packages = ["{mod}"]

# The scaffolded audit test guards schema/prompt drift; `uv run pytest` needs it.
[dependency-groups]
dev = ["pytest>=8.0"]
'''


def _offer_bootstrap(mod: str) -> bool:
    """With no pyproject.toml there is nothing to install into, so the entry
    point can never resolve. Offer to write a minimal packaged project so the
    scaffold is runnable. Returns True if one was written."""
    pyproject = Path.cwd() / "pyproject.toml"
    if pyproject.exists():
        return False
    print("\n  No pyproject.toml here, so there's nothing for the project to be "
          "installed into\n  (an entry point only resolves from an installed package).")
    if not _ask(f"  Create a minimal one packaging '{mod}'?", default=True):
        return False
    name = to_module_name(Path.cwd().name) or "my-project"
    pyproject.write_text(BOOTSTRAP_PYPROJECT.format(name=name.replace("_", "-"), mod=mod))
    print(f"  Wrote pyproject.toml (project '{name}', packaging {mod}/).")
    return True


def _ask(question: str, default: bool) -> bool:
    suffix = " [Y/n] " if default else " [y/N] "
    ans = input(question + suffix).strip().lower()
    if not ans:
        return default
    return ans in ("y", "yes")


def init(name: str | None = None, *, install: bool = True) -> int:
    """Interactive scaffold. Asks input type + (for images) verso/crop, writes
    the project files under ./<module>/, offers to add a paratext.toml config
    entry, then (unless ``install`` is False) registers the entry point in
    pyproject.toml and runs ``uv sync``."""
    name = name or input("Project name: ").strip()
    if not name:
        raise SystemExit("a project name is required")

    is_pdf = _ask("Is the source PDFs (rather than images)?", default=False)
    kind = "pdf" if is_pdf else "images"
    verso = crop = False
    if kind == "images":
        # Both default to off: they are card-specific and calibrated to one
        # collection's scans, so they need checking against your own material.
        cards = _ask("Is the source scanned index cards?", default=False)
        if cards:
            print("    Note: both options below are calibrated on NLS cards —"
                  " check them against your own scans before trusting them.")
            verso = _ask("    Filter blank versos (backs of cards) before the model?",
                         default=False)
            crop = _ask("    Crop each scan to the card region"
                        " (needs the [detector] extra)?", default=False)

    raw = input("Metadata fields, comma-separated (e.g. title, author, date) [title]: ")
    fields = [f.strip() for f in raw.split(",") if f.strip()] or ["title"]

    mod = to_module_name(name)
    if install:
        _offer_bootstrap(mod)
    pkg_dir, pkg_name = detect_package()
    files = render_project(name, kind=kind, verso=verso, crop=crop, fields=fields,
                           pkg_dir=pkg_dir, pkg_name=pkg_name)
    where = f"{pkg_dir}/{mod}" if pkg_dir else mod
    dotted = f"{pkg_name}.{mod}" if pkg_name else mod
    dest = Path.cwd() / where
    if dest.exists():
        raise SystemExit(f"refusing to overwrite existing directory: {dest}")
    for rel, content in files.items():
        path = Path.cwd() / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)

    ep_name = mod.replace("_", "-")
    print(f"\nCreated ./{where}/ (schema.py + prompt.md + __init__.py) "
          f"and tests/test_{mod}_audit.py.")
    if pkg_name:
        print(f"  Nested inside the '{pkg_name}' package so it ships with it.")

    _offer_config(ep_name)
    registered = _register_and_sync(dotted, ep_name, install)

    print("\nNext steps:")
    n = 1
    if not registered:
        print(f"  {n}. Register the project — add to your pyproject.toml:")
        print('       [project.entry-points."paratext.projects"]')
        print(f'       {ep_name} = "{dotted}:PROJECT"')
        print("     then reinstall:  uv sync   (or: pip install -e .)")
        n += 1
    print(f"  {n}. Edit {where}/prompt.md and {where}/schema.py (keep them in step).")
    print(f"  {n + 1}. Run it:  paratext run -p {ep_name}")
    print(f"  {n + 2}. Guard schema/prompt drift:  uv run pytest tests/test_{mod}_audit.py")
    return 0


def _insert_entry_point(pyproject: Path, text: str, ep_name: str, mod: str) -> bool:
    """Add `ep_name = "<mod>:PROJECT"` under the paratext.projects entry-point
    table, creating the table if absent. Returns False if it can't do so safely."""
    line = f'{ep_name} = "{mod}:PROJECT"'
    header_re = re.compile(
        r'^\[project\.entry-points\.["\']paratext\.projects["\']\]\s*$', re.M
    )
    m = header_re.search(text)
    if m:
        pyproject.write_text(text[: m.end()] + "\n" + line + text[m.end():])
        return True
    if "paratext.projects" in text:
        return False  # a table exists but in a form we won't risk editing
    sep = "" if text.endswith("\n") else "\n"
    pyproject.write_text(text + f'{sep}\n[project.entry-points."paratext.projects"]\n{line}\n')
    return True


def _register_and_sync(mod: str, ep_name: str, install: bool) -> bool:
    """Register the entry point in pyproject.toml and run `uv sync` — the
    mechanical steps to make the project runnable, done without prompting. Skipped
    by `--no-install` or when there's no pyproject.toml. Returns True if
    registered."""
    import tomllib

    pyproject = Path.cwd() / "pyproject.toml"
    if not install or not pyproject.exists():
        return False  # nothing to install into; init() prints the manual steps
    text = pyproject.read_text()
    try:
        parsed = tomllib.loads(text)
    except tomllib.TOMLDecodeError:
        return False
    eps = (parsed.get("project", {}).get("entry-points", {}) or {}).get("paratext.projects", {})

    if ep_name in (eps or {}):
        print(f"  '{ep_name}' is already registered in pyproject.toml.")
    elif _insert_entry_point(pyproject, text, ep_name, mod):
        print(f"  Registered '{ep_name}' in pyproject.toml.")
    else:
        print("  Couldn't safely edit pyproject.toml — add the entry point by hand.")
        return False

    import shutil
    import subprocess

    if shutil.which("uv"):
        print("  Reinstalling (uv sync)…")
        subprocess.call(["uv", "sync"])
        # Confirm it's actually importable/discovered (catches src-layout packages
        # where a module in the repo root isn't installed).
        check = subprocess.run(
            ["uv", "run", "python", "-c",
             f"from paratext.projects import project_names as p; "
             f"import sys; sys.exit(0 if '{ep_name}' in p() else 1)"],
        )
        if check.returncode != 0:
            # Registered but not installed. Almost always the build config: the
            # module is on disk and in pyproject, but the wheel doesn't ship it.
            print(f"\n  ! '{ep_name}' still isn't discovered, so `paratext run -p "
                  f"{ep_name}` won't work yet.")
            print(f"    {mod.split('.')[0]}/ has to be part of what your project "
                  "packages. Check the build\n    config in pyproject.toml — e.g. for "
                  "hatchling:")
            print(f'        [tool.hatch.build.targets.wheel]\n        packages = '
                  f'["{mod.split(".")[0]}"]')
            print("    then re-run `uv sync`.")
    else:
        print("  uv not found — run `pip install -e .` to reinstall.")
    return True


def _offer_config(ep_name: str) -> None:
    """Optionally write a `[project.<name>]` block (and a top-level endpoint if the
    config has none) to paratext.toml, so the project is runnable without a
    separate `paratext config` trip."""
    import tomllib

    from .config import local_config_path

    if not _ask(f"Add a paratext.toml config entry for '{ep_name}' now?", default=True):
        return

    path = local_config_path()
    existing = path.read_text() if path.exists() else ""
    parsed = tomllib.loads(existing) if existing.strip() else {}
    if ep_name in (parsed.get("project") or {}):
        print(f"  paratext.toml already has [project.{ep_name}] — leaving it as is.")
        return

    source = input("  Source directory (images or PDFs) []: ").strip()

    block: list[str] = []
    if not existing.strip():
        block.append("# paratext config")
    if not any(k in parsed for k in ("base-url", "base_url")):
        base = input("  model base URL [http://localhost:8000/v1]: ").strip() \
            or "http://localhost:8000/v1"
        model = input("  Model id served by that endpoint []: ").strip()
        block.append(f'base-url = "{base}"')
        if model:
            block.append(f'model = "{model}"')
        block.append("")
    block.append(f"[project.{ep_name}]")
    block.append(f'source = "{source}"' if source else '# source = "path/to/your/data"')

    sep = "\n" if existing.strip() else ""
    with path.open("a") as f:
        f.write(sep + "\n".join(block) + "\n")
    print(f"  Wrote [project.{ep_name}] to {path}.")
